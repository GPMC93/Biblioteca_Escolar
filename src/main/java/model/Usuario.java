package model;

/*
 * Clase base abstracta para los usuarios del sistema de biblioteca
 * Contiene los datos comunes de los distintos tipos de usuario
 */
public abstract class Usuario implements PermisosUsuario {

    private int id;
    private String nombre;
    private String rut;
    private String correo;
    private String contrasena;
    private Rol rol;

    public Usuario(String nombre, String rut, String correo,
                   String contrasena, Rol rol) {
        this.nombre = nombre;
        this.rut = rut;
        this.correo = correo;
        this.contrasena = contrasena;
        this.rol = rol;
    }

    public Usuario(int id, String nombre, String rut, String correo,
                   String contrasena, Rol rol) {
        this.id = id;
        this.nombre = nombre;
        this.rut = rut;
        this.correo = correo;
        this.contrasena = contrasena;
        this.rol = rol;
    }

    public int getId() {
        return id;
    }

    public String getNombre() {
        return nombre;
    }

    public String getRut() {
        return rut;
    }

    public String getCorreo() {
        return correo;
    }

    public String getContrasena() {
        return contrasena;
    }

    public Rol getRol() {
        return rol;
    }

    public void setId(int id) {
        this.id = id;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public void setRut(String rut) {
        this.rut = rut;
    }

    public void setCorreo(String correo) {
        this.correo = correo;
    }

    public void setContrasena(String contrasena) {
        this.contrasena = contrasena;
    }

    public void setRol(Rol rol) {
        this.rol = rol;
    }
}